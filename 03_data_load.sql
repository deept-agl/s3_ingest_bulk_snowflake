USE WAREHOUSE DEV_WH;
USE DATABASE ECOMMERCE_DB;
USE SCHEMA RAW;

COPY INTO ECOMMERCE_DB.RAW.PRODUCTS
FROM @ECOMMERCE_S3_KEY_STAGE/products/
FILE_FORMAT = (FORMAT_NAME = ECOMMERCE_CSV_LOAD_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';

SELECT * FROM PRODUCTS;

--Check Copy history
SELECT *
FROM TABLE(
    INFORMATION_SCHEMA.COPY_HISTORY(
        TABLE_NAME => 'ECOMMERCE_DB.RAW.PRODUCTS',
        START_TIME => DATEADD('DAY', -7, CURRENT_TIMESTAMP())
    )
);

--similarly load orders
CREATE TABLE IF NOT EXISTS ORDERS
USING TEMPLATE (
    SELECT ARRAY_AGG(
        OBJECT_CONSTRUCT(
            'COLUMN_NAME', COLUMN_NAME,
            'TYPE', TYPE,
            'NULLABLE', NULLABLE
        )
    ) WITHIN GROUP (ORDER BY ORDER_ID)
    FROM TABLE(
        INFER_SCHEMA(
            LOCATION => '@ECOMMERCE_S3_KEY_STAGE/orders/',
            FILE_FORMAT => 'ECOMMERCE_CSV_INFER_FORMAT',
            IGNORE_CASE => TRUE
        )
    )
);

COPY INTO ECOMMERCE_DB.RAW.ORDERS
FROM @ECOMMERCE_S3_KEY_STAGE/orders/
FILE_FORMAT = (FORMAT_NAME = ECOMMERCE_CSV_LOAD_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';


SELECT * FROM ORDERS;