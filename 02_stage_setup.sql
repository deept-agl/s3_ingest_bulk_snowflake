USE WAREHOUSE DEV_WH;
USE DATABASE ECOMMERCE_DB;
USE SCHEMA RAW;


CREATE STAGE ECOMMERCE_S3_KEY_STAGE
    URL = 's3://retail-dataset-snowflake-ingestion/ecommerce/'
    CREDENTIALS = (
        AWS_KEY_ID = ''
        AWS_SECRET_KEY = ''
    );

LIST @ECOMMERCE_S3_KEY_STAGE;

LIST @ECOMMERCE_S3_KEY_STAGE/products/;

CREATE OR REPLACE FILE FORMAT ECOMMERCE_CSV_INFER_FORMAT
  TYPE = CSV
  PARSE_HEADER = TRUE
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = TRUE
  TIMESTAMP_FORMAT = 'DD-MM-YYYY HH24:MI';

CREATE OR REPLACE FILE FORMAT ECOMMERCE_CSV_LOAD_FORMAT
  TYPE = CSV
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = TRUE;


-- Infer Products schema
SELECT *
FROM TABLE(
    INFER_SCHEMA(
        LOCATION => '@ECOMMERCE_S3_KEY_STAGE/products/',
        FILE_FORMAT => 'ECOMMERCE_CSV_INFER_FORMAT',
        IGNORE_CASE => TRUE
    )
);


CREATE TABLE IF NOT EXISTS PRODUCTS
USING TEMPLATE (
    SELECT ARRAY_AGG(
        OBJECT_CONSTRUCT(
            'COLUMN_NAME', COLUMN_NAME,
            'TYPE', TYPE,
            'NULLABLE', NULLABLE
        )
    ) WITHIN GROUP (ORDER BY ORDER_ID)
    FROM TABLE(
        INFER_SCHEMA(
            LOCATION => '@ECOMMERCE_S3_KEY_STAGE/products/',
            FILE_FORMAT => 'ECOMMERCE_CSV_INFER_FORMAT',
            IGNORE_CASE => TRUE
        )
    )
);

select * from products;