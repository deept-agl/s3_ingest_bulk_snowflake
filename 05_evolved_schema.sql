USE WAREHOUSE DEV_WH;
USE DATABASE ECOMMERCE_DB;
USE SCHEMA RAW;


ALTER TABLE ECOMMERCE_DB.RAW.ORDERS
SET ENABLE_SCHEMA_EVOLUTION = TRUE;

SELECT *
FROM TABLE(
    INFER_SCHEMA(
        LOCATION => '@ECOMMERCE_S3_KEY_STAGE/orders/',
        FILE_FORMAT => 'ECOMMERCE_CSV_INFER_FORMAT',
        IGNORE_CASE => TRUE
    )
);

DESC TABLE ECOMMERCE_DB.RAW.ORDERS;

COPY INTO ECOMMERCE_DB.RAW.ORDERS
FROM @ECOMMERCE_S3_KEY_STAGE/orders/
FILE_FORMAT = (
    FORMAT_NAME = ECOMMERCE_CSV_INFER_FORMAT
)
MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
ON_ERROR = 'ABORT_STATEMENT'
FORCE = FALSE;

select * from orders where discount is not null limit 10;